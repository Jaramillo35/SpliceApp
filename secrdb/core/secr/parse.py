def _connector_rows(ws, sheet_name: str) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    for block in _blocks_of_kind(ws, OBJECT_CONNECTOR):
        headers = block.headers
        for row in range(block.first_row, block.last_row + 1):
            action = _cell(ws, row, headers, "Action").upper()
            cnum = _cell(ws, row, headers, "FCA-CNUM")
            if action not in FILE_ACTIONS or not cnum:
                continue
            rows.append(
                {
                    "sheet": sheet_name,
                    "row": row,
                    "action": action,
                    "cnum": cnum,
                    "pn_new": _cell(ws, row, headers, "DEF_Connector_PN"),
                    "pn_old": _cell(
                        ws,
                        row,
                        headers,
                        "DEF_Connector_PN(Old)",
                        "DEF_Connector_PN (Old)",
                    ),
                    "suffix_new": _cell(ws, row, headers, "Suffix(New)", "Suffix (New)"),
                    "suffix_old": _cell(ws, row, headers, "Suffix(Old)", "Suffix (Old)"),
                    "supplier": _cell(ws, row, headers, "DEF_Connector_Supplier"),
                    "se_comment": _se_comment(ws, row, headers),
                }
            )
    return rows


def _pair_pn_changes(
    rows: List[Dict[str, Any]]
) -> Tuple[List[Tuple[Dict[str, Any], Dict[str, Any]]], List[Dict[str, Any]]]:
    """Pair a DELETE with an ADD of the same CNUM into a part-number change."""
    by_cnum: Dict[str, Dict[str, List[Dict[str, Any]]]] = {}
    for row in rows:
        by_cnum.setdefault(row["cnum"], {}).setdefault(row["action"], []).append(row)

    pairs: List[Tuple[Dict[str, Any], Dict[str, Any]]] = []
    paired: set[int] = set()
    for actions in by_cnum.values():
        deletes = actions.get("DELETE", [])
        adds = actions.get("ADD", [])
        for deleted, added in zip(deletes, adds):
            pairs.append((deleted, added))
            paired.add(id(deleted))
            paired.add(id(added))
    unpaired = [row for row in rows if id(row) not in paired]
    return pairs, unpaired


def _dedupe_rows(
    primary: List[Dict[str, Any]], secondary: List[Dict[str, Any]], *keys: str
) -> List[Dict[str, Any]]:
    """``primary`` plus any ``secondary`` row it does not already cover.

    The same change is often written to two sheets (a connector DELETE appears
    on both ``Add_Remove_Report_Summary`` and ``Connector``). Taking the union
    and dropping exact key matches counts each change once without assuming one
    sheet is always a superset of the other — if a file ever disagrees, the
    extra rows are kept rather than silently dropped.
    """
    seen = {tuple(row[key] for key in keys) for row in primary}
    merged = list(primary)
    for row in secondary:
        signature = tuple(row[key] for key in keys)
        if signature not in seen:
            seen.add(signature)
            merged.append(row)
    return merged


def _parse_connectors(wb) -> Tuple[List[ParsedChange], List[str]]:
    """Connector adds/deletes/PN changes plus in-place connector changes.

    Adds and deletes are taken from ``Add_Remove_Report_Summary`` — verified
    across the historical corpus to be a superset of the ``Connector`` sheet's
    add/delete rows — and the ``Connector`` sheet contributes its CHG /
    COMP CHG rows plus anything the add/remove report happens to be missing.
    """
    changes: List[ParsedChange] = []
    warnings: List[str] = []

    add_remove_rows: List[Dict[str, Any]] = []
    if ADD_REMOVE_SHEET in wb.sheetnames:
        add_remove_rows = _connector_rows(wb[ADD_REMOVE_SHEET], ADD_REMOVE_SHEET)

    connector_rows: List[Dict[str, Any]] = []
    if CONNECTOR_SHEET in wb.sheetnames:
        connector_rows = _connector_rows(wb[CONNECTOR_SHEET], CONNECTOR_SHEET)

    connector_add_delete = [
        row for row in connector_rows if row["action"] in ("ADD", "DELETE")
    ]
    add_remove_rows = _dedupe_rows(
        add_remove_rows, connector_add_delete, "action", "cnum"
    )

    pairs, unpaired = _pair_pn_changes(add_remove_rows)

    for deleted, added in pairs:
        comment = added["se_comment"] or deleted["se_comment"]
        changes.append(
            ParsedChange(
                object_type=OBJECT_CONNECTOR,
                object_id=added["cnum"],
                action=ACTION_PN_CHANGE,
                field="DEF_Connector_PN",
                old_value=_optional(deleted["pn_old"] or deleted["pn_new"]),
                new_value=_optional(added["pn_new"]),
                dtcr_number=_row_dtcrs(comment),
                se_comment=_optional(comment),
                source_sheet=added["sheet"],
                source_row=added["row"],
            )
        )
        if added["suffix_new"] != deleted["suffix_old"]:
            changes.append(
                ParsedChange(
                    object_type=OBJECT_CONNECTOR,
                    object_id=added["cnum"],
                    action=ACTION_PN_CHANGE,
                    field="Suffix",
                    old_value=_optional(deleted["suffix_old"]),
                    new_value=_optional(added["suffix_new"]),
                    dtcr_number=_row_dtcrs(comment),
                    se_comment=_optional(comment),
                    source_sheet=added["sheet"],
                    source_row=added["row"],
                )
            )

    for row in unpaired:
        is_add = row["action"] == "ADD"
        changes.append(
            ParsedChange(
                object_type=OBJECT_CONNECTOR,
                object_id=row["cnum"],
                action=row["action"],
                field="DEF_Connector_PN",
                old_value=None if is_add else _optional(row["pn_old"] or row["pn_new"]),
                new_value=_optional(row["pn_new"]) if is_add else None,
                dtcr_number=_row_dtcrs(row["se_comment"]),
                se_comment=_optional(row["se_comment"]),
                source_sheet=row["sheet"],
                source_row=row["row"],
            )
        )

    for row in connector_rows:
        if row["action"] not in ("CHG", "COMP CHG"):
            continue
        emitted = False
        for label, old, new in (
            ("DEF_Connector_PN", row["pn_old"], row["pn_new"]),
            ("Suffix", row["suffix_old"], row["suffix_new"]),
        ):
            if old != new and (old or new):
                emitted = True
                changes.append(
                    ParsedChange(
                        object_type=OBJECT_CONNECTOR,
                        object_id=row["cnum"],
                        action=row["action"],
                        field=label,
                        old_value=_optional(old),
                        new_value=_optional(new),
                        dtcr_number=_row_dtcrs(row["se_comment"]),
                        se_comment=_optional(row["se_comment"]),
                        source_sheet=row["sheet"],
                        source_row=row["row"],
                    )
                )
        if not emitted:
            # A marked change we cannot attribute to a field — record it rather
            # than dropping it, with the SE comment as the only evidence.
            changes.append(
                ParsedChange(
                    object_type=OBJECT_CONNECTOR,
                    object_id=row["cnum"],
                    action=row["action"],
                    field=None,
                    old_value=None,
                    new_value=None,
                    dtcr_number=_row_dtcrs(row["se_comment"]),
                    se_comment=_optional(row["se_comment"]),
                    source_sheet=row["sheet"],
                    source_row=row["row"],
                )
            )
    return changes, warnings


