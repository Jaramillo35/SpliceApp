#: Summary affected-item category -> the change object_type that backs it. The
#: ``part_number`` block is excluded: it holds free text ("Symbols 447, 448")
#: that does not map one-to-one onto a change row.
_RECONCILE_CATEGORIES = {"device": OBJECT_CONNECTOR, "circuit": OBJECT_CIRCUIT}


def _reconcile_summary(
    affected_items: List[Dict[str, str]], changes: List[ParsedChange]
) -> List[str]:
    """Flag Summary roll-up entries that no change row accounts for.

    The Summary block and the change sheets are written by the same generator,
    so they normally agree. When they don't — a hand-edited Summary, or a
    workbook rebuilt against a different DEF — the roll-up is the only record
    that the item was touched. Both are kept; this warning makes the gap
    visible instead of letting the detail view look complete.
    """
    warnings: List[str] = []
    for category, object_type in _RECONCILE_CATEGORIES.items():
        listed = {
            item["item"] for item in affected_items if item["category"] == category
        }
        backed = {
            change.object_id for change in changes if change.object_type == object_type
        }
        missing = sorted(listed - backed)
        if missing:
            shown = ", ".join(missing[:10])
            more = f" (+{len(missing) - 10} more)" if len(missing) > 10 else ""
            warnings.append(
                f"Summary lists {len(missing)} {category} item(s) with no matching "
                f"row on the change sheets: {shown}{more}."
            )
    return warnings


def parse_secr_bytes(secr_bytes: bytes, *, filename: str = "") -> ParsedSecr:
    """Parse a SECR workbook into metadata + normalized change records.

    Raises :class:`SpliceSchemaError` when the file is not a SECR workbook (no
    ``Summary`` sheet) or carries no SECR number, which is the identity the
    database is keyed on.
    """
    if not secr_bytes:
        raise SpliceSchemaError("The SECR file is empty.")
    try:
        workbook = openpyxl.load_workbook(io.BytesIO(secr_bytes), data_only=True)
    except Exception as exc:  # noqa: BLE001 - any openpyxl failure is a bad file
        raise SpliceSchemaError(
            f"Could not read '{filename or 'the file'}' as an Excel workbook: {exc}"
        ) from exc

    try:
        if SUMMARY_SHEET not in workbook.sheetnames:
            raise SpliceSchemaError(
                f"'{filename or 'The file'}' has no '{SUMMARY_SHEET}' sheet, so it is "
                "not a SECR workbook."
            )
        metadata, affected_items = _parse_summary(workbook[SUMMARY_SHEET])
        secr_number = metadata.get("secr_number", "")
        if not secr_number:
            raise SpliceSchemaError(
                f"'{filename or 'The file'}' has no SECR # in Summary!I2."
            )

        changes: List[ParsedChange] = []
        warnings: List[str] = []
        for parser in (_parse_connectors, _parse_circuits, _parse_harness_pns):
            parsed_changes, parsed_warnings = parser(workbook)
            changes.extend(parsed_changes)
            warnings.extend(parsed_warnings)
    finally:
        workbook.close()

    dtcr_numbers = split_list(metadata.get("dtcr_numbers"))
    for change in changes:
        if change.dtcr_number and change.dtcr_number not in dtcr_numbers:
            dtcr_numbers.append(change.dtcr_number)

    if not changes:
        warnings.append(
            "No change rows were found on the Connector / Circuit / "
            "DEF_DEF_Summary sheets."
        )
    warnings.extend(_reconcile_summary(affected_items, changes))

    return ParsedSecr(
        secr_number=secr_number,
        version=metadata.get("version") or "A",
        metadata=metadata,
        affected_items=affected_items,
        changes=changes,
        dtcr_numbers=dtcr_numbers,
        bulletin_numbers=split_list(metadata.get("bulletin_numbers")),
        warnings=warnings,
        source_sha256=hashlib.sha256(secr_bytes).hexdigest(),
        source_size=len(secr_bytes),
    )


def summarize_changes(changes: Iterable[ParsedChange]) -> Dict[str, int]:
    """Count changes by action — used by the import report and the dashboard."""
    counts: Dict[str, int] = {}
    for change in changes:
        counts[change.action] = counts.get(change.action, 0) + 1
    return counts
