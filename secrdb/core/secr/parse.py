def _circuit_changed_fields(
    ws, row: int, headers: Dict[str, int], header_row: int, action: str
) -> List[Tuple[str, Optional[str], Optional[str]]]:  # noqa: C901
    """Return ``(field, old_value, new_value)`` for each changed circuit field."""
    results: List[Tuple[str, Optional[str], Optional[str]]] = []
    for col in range(1, (ws.max_column or 1) + 1):
        header = _header_text(ws.cell(header_row, col).value)
        if not header or header in _CIRCUIT_IGNORED:
            continue
        if header.endswith("(Old)"):
            continue  # consumed as the old value of its twin
        # Trailing numeric columns are the per-harness variant matrix (X marks),
        # not engineering values.
        if re.fullmatch(r"\d+", header):
            continue

        cell = ws.cell(row, col)
        new_value = _text(cell.value)
        old_header = _CIRCUIT_OLD_PAIRS.get(header)
        old_value: Optional[str] = None
        changed = False

        if old_header and old_header in headers:
            old_value = _text(ws.cell(row, headers[old_header]).value)
            changed = old_value != new_value
            if action in ("ADD", "DELETE"):
                changed = bool(new_value or old_value)
        elif action in ("CHG", "COMP CHG"):
            if _is_marked_changed(cell):
                changed = True
                old_value = _old_value_from_comment(cell)
        else:  # ADD / DELETE: the whole row is the change
            changed = bool(new_value)

        if not changed:
            continue
        if action == "DELETE":
            results.append((header, _optional(new_value), None))
        elif action == "ADD":
            results.append((header, None, _optional(new_value)))
        else:
            results.append((header, _optional(old_value or ""), _optional(new_value)))
    return results


def _parse_circuit_blocks(ws, sheet_name: str) -> Tuple[List[ParsedChange], int]:
    changes: List[ParsedChange] = []
    unattributed = 0
    for block in _blocks_of_kind(ws, OBJECT_CIRCUIT):
        headers = block.headers
        for row in range(block.first_row, block.last_row + 1):
            action = _cell(ws, row, headers, "Action").upper()
            number = _cell(ws, row, headers, "CKT NBR")
            if action not in FILE_ACTIONS or not number:
                continue
            # The circuit identity engineers use (and that the Summary rollup
            # writes) is CKT NBR + CKT Suffix, e.g. A937 + F -> "A937F".
            circuit = number + _cell(ws, row, headers, "CKT Suffix")
            comment = _se_comment(ws, row, headers)
            dtcr = _row_dtcrs(comment)
            sales_code = _cell(ws, row, headers, "Sales_Code")
            # The endpoints belong to the circuit *row*, so every changed field
            # from that row carries them. That is what lets a DTCR be related
            # to a circuit together with the connectors and cavities it lands
            # on, without inventing a second row per endpoint.
            from_dnum, from_cav = split_endpoint(
                _endpoint_cell(ws, row, headers, "FROM")
            )
            to_dnum, to_cav = split_endpoint(
                _endpoint_cell(ws, row, headers, "TO")
            )
            fields = _circuit_changed_fields(
                ws, row, headers, block.header_row, action
            )
            # If an endpoint is what changed, its previous connector/cavity is
            # in that field's old value; otherwise the pin did not move and the
            # previous state is the current one.
            previous = _previous_endpoints(fields)
            from_dnum_old, from_cav_old = previous.get(
                "FROM", (from_dnum, from_cav)
            )
            to_dnum_old, to_cav_old = previous.get("TO", (to_dnum, to_cav))
            if not fields:
                unattributed += 1
                fields = [(None, None, None)]  # keep the row, flag the gap
            for field_name, old_value, new_value in fields:
                changes.append(
                    ParsedChange(
                        object_type=OBJECT_CIRCUIT,
                        object_id=circuit,
                        action=action,
                        field=field_name,
                        old_value=old_value,
                        new_value=new_value,
                        dtcr_number=dtcr,
                        sales_code=_optional(sales_code),
                        se_comment=_optional(comment),
                        source_sheet=sheet_name,
                        source_row=row,
                        from_dnum=from_dnum,
                        from_cav=from_cav,
                        to_dnum=to_dnum,
                        to_cav=to_cav,
                        from_dnum_old=from_dnum_old,
                        from_cav_old=from_cav_old,
                        to_dnum_old=to_dnum_old,
                        to_cav_old=to_cav_old,
                    )
                )
    return changes, unattributed


def _parse_circuits(wb) -> Tuple[List[ParsedChange], List[str]]:
    """Circuit changes, from the ``Circuit`` sheet and the add/remove report.

    The ``Circuit`` sheet is the richer source — it carries the CHG / COMP CHG
    rows and the paired ``(Old)`` columns — so it is read first and wins on
    conflict. The circuit block of ``Add_Remove_Report_Summary`` normally
    repeats its ADD/DELETE rows exactly; taking the union and deduping on
    circuit + action keeps that from double counting, while still capturing an
    add or delete that only one of the two sheets happens to record.
    """
    changes: List[ParsedChange] = []
    warnings: List[str] = []
    unattributed = 0

    if CIRCUIT_SHEET in wb.sheetnames:
        changes, unattributed = _parse_circuit_blocks(wb[CIRCUIT_SHEET], CIRCUIT_SHEET)

    if ADD_REMOVE_SHEET in wb.sheetnames:
        extra, extra_unattributed = _parse_circuit_blocks(
            wb[ADD_REMOVE_SHEET], ADD_REMOVE_SHEET
        )
        covered = {(c.object_id, c.action) for c in changes}
        new_rows = [c for c in extra if (c.object_id, c.action) not in covered]
        if new_rows:
            changes.extend(new_rows)
            unattributed += extra_unattributed

    if unattributed:
        warnings.append(
            f"{unattributed} circuit row(s) are marked changed but no changed "
            "field could be identified; recorded without old/new values."
        )
    return changes, warnings


# ---------------------------------------------------------------------------
# Harness part numbers (DEF_DEF_Summary)
# ---------------------------------------------------------------------------

def _parse_harness_pns(wb) -> Tuple[List[ParsedChange], List[str]]:
    changes: List[ParsedChange] = []
    warnings: List[str] = []
    if DEF_DEF_SUMMARY_SHEET not in wb.sheetnames:
        return changes, warnings

    ws = wb[DEF_DEF_SUMMARY_SHEET]
    blocks = _blocks_of_kind(ws, OBJECT_HARNESS)
    if not blocks:
        warnings.append(
            f"'{DEF_DEF_SUMMARY_SHEET}' sheet has no 'Harness PN' header; skipped."
        )
        return changes, warnings

    for block in blocks:
        headers = block.headers
        for row in range(block.first_row, block.last_row + 1):
            action = _cell(ws, row, headers, "Action").upper()
            if action not in FILE_ACTIONS:
                continue
            symbol = _cell(ws, row, headers, "DEF Symbol")
            pn_new = _cell(ws, row, headers, "Harness PN")
            pn_old = _cell(ws, row, headers, "Harness PN (Old)", "Harness PN(Old)")
            if not (symbol or pn_new or pn_old):
                continue
            comment = _se_comment(ws, row, headers)
            changes.append(
                ParsedChange(
                    object_type=OBJECT_HARNESS,
                    object_id=symbol or pn_new or pn_old,
                    action=action,
                    field="Harness PN",
                    old_value=_optional(pn_old),
                    new_value=_optional(pn_new),
                    dtcr_number=_row_dtcrs(comment),
                    harness_pn=_optional(pn_new or pn_old),
                    se_comment=_optional(comment),
                    source_sheet=DEF_DEF_SUMMARY_SHEET,
                    source_row=row,
                )
            )
    return changes, warnings


