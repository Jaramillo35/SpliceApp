"""SECR workbook parser — turns a SECR .xlsx into structured engineering data.

This is the read side of the SECR database: it takes the bytes of a SECR
workbook (generated by :mod:`secrdb.core.secr.generate`, or an historical file an
engineer drops into the import panel) and returns a :class:`ParsedSecr` holding
the Summary metadata plus one :class:`ParsedChange` per *changed field*.

Where the data lives in a SECR workbook
---------------------------------------
``Summary``
    Header metadata (SECR #, version, MY, vehicle line, phase, harness family,
    DTCR #s, bulletin #s) and the affected-item roll-up blocks.
``Add_Remove_Report_Summary``
    Connector ADD / DELETE rows. Verified superset of the ADD/DELETE rows on
    the ``Connector`` sheet, so connector adds and deletes are read from here
    only — otherwise every add would be counted twice.
``Connector``
    Connector CHG / COMP CHG rows, with explicit ``(Old)`` columns.
``Circuit``
    Circuit ADD / DELETE / CHG / COMP CHG rows. Old values come from an
    explicit ``(Old)`` column where the sheet has one; otherwise from the cell
    comment the compare engine writes (``"Old DEF :X350A|1"``). Changed cells
    are additionally highlighted yellow.
``DEF_DEF_Summary``
    Harness-level part-number changes, one row per DEF symbol.

Nothing here invents values. A field whose old value cannot be recovered is
recorded with ``old_value=None`` and the record carries a warning, so the UI
can show the gap instead of a fabricated number.
"""

from __future__ import annotations

import hashlib
import io
import re
from dataclasses import dataclass, field as dataclass_field
from typing import Any, Dict, Iterable, List, Optional, Tuple

import openpyxl

from secrdb.core.common.errors import SpliceSchemaError

SUMMARY_SHEET = "Summary"
CONNECTOR_SHEET = "Connector"
CIRCUIT_SHEET = "Circuit"
ADD_REMOVE_SHEET = "Add_Remove_Report_Summary"
DEF_DEF_SUMMARY_SHEET = "DEF_DEF_Summary"

#: Action vocabulary as written by the compare engine into the SECR sheets.
FILE_ACTIONS = frozenset({"ADD", "DELETE", "CHG", "COMP CHG"})

#: Derived action: a DELETE and an ADD of the same CNUM in one SECR is how the
#: workbooks express "this connector's part number was replaced".
ACTION_PN_CHANGE = "PN CHANGE"

OBJECT_CONNECTOR = "connector"
OBJECT_CIRCUIT = "circuit"
OBJECT_PART_NUMBER = "part_number"
OBJECT_HARNESS = "harness"

#: Yellow fills used by the compare engine to mark a changed cell.
_YELLOW_FILLS = frozenset({"FFFFFF00", "FFFF00", "FFFFFF99"})

#: A DTCR is any standalone 5-digit number in an SE Comment.
#:
#: This deliberately does NOT require the word "DTCR". SEs write the number a
#: dozen ways — ``DTCR 49793``, ``DTCR-50326``, ``DTCR_50073``, ``DTCR D50351 &
#: D50298``, ``DTCR 50298 AND 50318``, and bare lists like ``Delete PHEV:
#: 49900/49951/49745`` — and a keyword-anchored pattern missed most of them.
#:
#: The width is exactly 5 because that is what separates a DTCR from the other
#: numbers in these comments: bulletins and part numbers are 6+ digits
#: (``320767``, ``318725``), cavities and gauges are 1-2. The lookarounds stop
#: a 5-digit run from being cut out of a longer number, so ``318725`` and
#: ``06092026`` contribute nothing.
_DTCR_RE = re.compile(r"(?<!\d)\d{5}(?!\d)")

# Summary cells, mirroring splice.secr.db.record_from_workbook.
_SUMMARY_CELLS = {
    "secr_number": "I2",
    "version": "I3",
    "workbook_name": "C8",
    "subject": "C7",
    "model_year": "C10",
    "program": "C11",
    "phase": "F10",
    "harness_family": "C12",
    "phase_implemented": "F11",
    "pull_ahead": "F12",
    "secr_author": "I10",
    "design_release_engineer": "I11",
    "change_requested_by": "I12",
    "dtcr_numbers": "C14",
    "bulletin_numbers": "G14",
    "ref_secr": "C15",
}

_AFFECTED_CELLS = [
    ("device", "ADD", "C20"),
    ("device", "CHG", "C21"),
    ("device", "DELETE", "C22"),
    ("circuit", "ADD", "C25"),
    ("circuit", "CHG", "C26"),
    ("circuit", "DELETE", "C27"),
    ("part_number", "ADD", "C30"),
    ("part_number", "CHG", "C31"),
    ("part_number", "DELETE", "C32"),
]

# Circuit columns that carry an explicit "old" twin. Everything else falls back
# to the cell comment.
_CIRCUIT_OLD_PAIRS = {
    "DEF CKT COLOR": "DEF CKT COLOR(Old)",
    "DEF GAUGE": "DEF GAUGE(Old)",
    "DEF_CKT_MATERIAL": "DEF_CKT_MATERIAL (Old)",
    "Sales_Code": "Sales_Code (Old)",
}

# Key/metadata columns that are never themselves a "changed field".
_CIRCUIT_IGNORED = frozenset(
    {"SE Comment", "SE Comments", "Action", "CKT NBR", "CKT Suffix"}
)


@dataclass(frozen=True)
class ParsedChange:
    """One changed field on one engineering object."""

    object_type: str
    object_id: str
    action: str
    source_sheet: str
    source_row: int
    field: Optional[str] = None
    old_value: Optional[str] = None
    new_value: Optional[str] = None
    dtcr_number: Optional[str] = None
    harness_pn: Optional[str] = None
    sales_code: Optional[str] = None
    se_comment: Optional[str] = None
    #: Where a circuit terminates, split out of ``CKT FROM/To (DNUM | CAV)``.
    #: A DNUM *is* an FCA-CNUM — the same connector namespace — so these make a
    #: circuit change findable by the connector it lands on. Circuit rows only.
    #:
    #: Both states are kept. A circuit *leaving* a pin is a change to that pin,
    #: so "has X501A cavity 7 changed?" has to see the row where the circuit
    #: moved away as well as the row where one arrived. The ``_old`` values
    #: equal their current twin unless that endpoint is what changed.
    from_dnum: Optional[str] = None
    from_cav: Optional[str] = None
    to_dnum: Optional[str] = None
    to_cav: Optional[str] = None
    from_dnum_old: Optional[str] = None
    from_cav_old: Optional[str] = None
    to_dnum_old: Optional[str] = None
    to_cav_old: Optional[str] = None


@dataclass
class ParsedSecr:
    """Everything the database stores about one SECR workbook."""

    secr_number: str
    version: str
    metadata: Dict[str, Any]
    affected_items: List[Dict[str, str]] = dataclass_field(default_factory=list)
    changes: List[ParsedChange] = dataclass_field(default_factory=list)
    dtcr_numbers: List[str] = dataclass_field(default_factory=list)
    bulletin_numbers: List[str] = dataclass_field(default_factory=list)
    warnings: List[str] = dataclass_field(default_factory=list)
    source_sha256: str = ""
    source_size: int = 0

    @property
    def change_count(self) -> int:
        return len(self.changes)


# ---------------------------------------------------------------------------
# Cell helpers
# ---------------------------------------------------------------------------

def _text(value: Any) -> str:
    if value is None:
        return ""
    if hasattr(value, "strftime"):
        return value.strftime("%Y-%m-%d")
    return str(value).strip()


def _header_text(value: Any) -> str:
    return re.sub(r"\s+", " ", _text(value)).strip()


def _optional(value: str) -> Optional[str]:
    return value or None


def split_list(text: Any) -> List[str]:
    """Split a comma/semicolon/newline separated cell into clean items."""
    raw = _text(text)
    if not raw:
        return []
    return [part.strip() for part in re.split(r"[,;\n]+", raw) if part.strip()]


def extract_dtcr_numbers(text: Any) -> List[str]:
    """Every DTCR named in a piece of free text, in the order written.

    A DTCR is any standalone 5-digit number — see :data:`_DTCR_RE` for why the
    word "DTCR" is not required and why 5 is the right width.
    """
    raw = _text(text)
    if not raw:
        return []
    found: List[str] = []
    for number in _DTCR_RE.findall(raw):
        if number not in found:
            found.append(number)
    return found


def _row_dtcrs(text: Any) -> Optional[str]:
    """The DTCRs for one change row, as stored in ``secr_change.dtcr_number``.

    A comment naming several DTCRs keeps all of them, comma-joined — the same
    shape :func:`secrdb.core.secr.generation.assign_dtcrs_to_cnums` already
    writes when the matching report ties one CNUM to several DTCRs. Keeping
    only the first silently dropped the rest, which made a DTCR that was always
    written second unqueryable.
    """
    numbers = extract_dtcr_numbers(text)
    return ", ".join(numbers) if numbers else None


def _is_marked_changed(cell) -> bool:
    """True when the compare engine marked this cell as the changed field."""
    try:
        rgb = cell.fill.fgColor.rgb
    except Exception:  # pragma: no cover - defensive, styles can be malformed
        rgb = None
    if rgb and str(rgb).upper() in _YELLOW_FILLS:
        return True
    return cell.comment is not None


def _old_value_from_comment(cell) -> Optional[str]:
    """Read the ``Old DEF :<value>`` comment the compare engine attaches."""
    if not cell.comment:
        return None
    text = (cell.comment.text or "").strip()
    match = re.search(r"old\s+def\s*:\s*(.*)", text, flags=re.IGNORECASE | re.DOTALL)
    value = match.group(1).strip() if match else text
    return value or None


#: Key column -> object kind. A header row is identified by carrying "Action"
#: plus exactly one of these keys.
_BLOCK_KEYS = {
    "FCA-CNUM": OBJECT_CONNECTOR,
    "CKT NBR": OBJECT_CIRCUIT,
    "Harness PN": OBJECT_HARNESS,
}


@dataclass(frozen=True)
class _Block:
    """One header row plus the data rows beneath it."""

    kind: str
    key_header: str
    header_row: int
    first_row: int
    last_row: int
    headers: Dict[str, int]


def _find_blocks(ws) -> List[_Block]:
    """Split a sheet into header-delimited blocks.

    Sheets are not laid out consistently: ``Add_Remove_Report_Summary`` holds
    *two* tables (a connector Add/Remove report followed by a circuit one),
    header rows sit on row 2 or 3 depending on the file, and a stray part
    number occasionally lands in an Action column. Finding the header rows
    first — rather than assuming row 3 and reading to the end of the sheet —
    keeps a circuit from being read as a connector.
    """
    max_row = ws.max_row or 0
    max_col = ws.max_column or 0
    candidates: List[Tuple[int, str, str, Dict[str, int]]] = []
    for row in range(1, max_row + 1):
        headers = {
            _header_text(ws.cell(row, col).value): col for col in range(1, max_col + 1)
        }
        headers.pop("", None)
        if "Action" not in headers:
            continue
        for key_header, kind in _BLOCK_KEYS.items():
            if key_header in headers:
                candidates.append((row, kind, key_header, headers))
                break

    blocks: List[_Block] = []
    for index, (header_row, kind, key_header, headers) in enumerate(candidates):
        next_header = (
            candidates[index + 1][0] if index + 1 < len(candidates) else max_row + 1
        )
        blocks.append(
            _Block(
                kind=kind,
                key_header=key_header,
                header_row=header_row,
                first_row=header_row + 1,
                last_row=next_header - 1,
                headers=headers,
            )
        )
    return blocks


def _blocks_of_kind(ws, kind: str) -> List[_Block]:
    return [block for block in _find_blocks(ws) if block.kind == kind]


def _cell(ws, row: int, headers: Dict[str, int], *names: str) -> str:
    for name in names:
        col = headers.get(name)
        if col:
            return _text(ws.cell(row, col).value)
    return ""


def _se_comment(ws, row: int, headers: Dict[str, int]) -> str:
    return _cell(ws, row, headers, "SE Comment", "SE Comments")


def _endpoint_cell(ws, row: int, headers: Dict[str, int], side: str) -> str:
    """The raw ``CKT FROM``/``CKT To`` cell, found by prefix.

    The two headers carry the same meaning but not the same spelling — the real
    workbooks write ``CKT FROM (DNUM | CAV)`` and ``CKT To (DNUM | CAV)``, one
    upper-case and one not — so they are matched case-insensitively by prefix
    rather than by an exact literal that a future template could break.
    """
    prefix = f"CKT {side}".upper()
    for name, col in headers.items():
        if name.upper().startswith(prefix):
            return _text(ws.cell(row, col).value)
    return ""


def endpoint_side(field_name: Any) -> Optional[str]:
    """``"CKT To (DNUM | CAV)"`` -> ``"TO"``; anything else -> ``None``."""
    header = _text(field_name).upper()
    if header.startswith("CKT FROM"):
        return "FROM"
    if header.startswith("CKT TO"):
        return "TO"
    return None


def _previous_endpoints(
    fields: List[Tuple[Optional[str], Optional[str], Optional[str]]],
) -> Dict[str, Tuple[Optional[str], Optional[str]]]:
    """Previous connector/cavity per side, for the sides that actually moved."""
    previous: Dict[str, Tuple[Optional[str], Optional[str]]] = {}
    for field_name, old_value, _new_value in fields:
        side = endpoint_side(field_name)
        if side and old_value:
            previous[side] = split_endpoint(old_value)
    return previous


def split_endpoint(value: Any) -> Tuple[Optional[str], Optional[str]]:
    """``"X501A|7"`` -> ``("X501A", "7")``. Returns ``(None, None)`` if unusable.

    The cavity is alphanumeric, not numeric: ``D3840A|C`` is as common as
    ``X501A|7`` (259 of the 5,636 endpoints in the validation set are lettered).
    """
    raw = _text(value)
    if "|" not in raw:
        return None, None
    dnum, _, cav = raw.partition("|")
    return (_optional(dnum.strip().upper()), _optional(cav.strip().upper()))


