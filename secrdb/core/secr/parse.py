def _parse_summary(ws) -> Tuple[Dict[str, Any], List[Dict[str, str]]]:
    metadata: Dict[str, Any] = {
        key: _text(ws[cell].value) for key, cell in _SUMMARY_CELLS.items()
    }
    metadata["original_issue_date"] = _text(ws["I4"].value)
    metadata["reissue_date"] = _text(ws["I5"].value)
    metadata["reason_for_change"] = _text(ws["B17"].value)

    affected: List[Dict[str, str]] = []
    for category, action, cell in _AFFECTED_CELLS:
        for item in split_list(ws[cell].value):
            affected.append({"category": category, "action": action, "item": item})
    return metadata, affected


